    public void loadInvoiceTable() {
        try {
            String search = searchTextField.getText();
            int sortBy = sortByComboBox.getSelectedIndex();

            String sortByColumn = "";
            String sortByType = "";

            if (sortBy == 0) {
                sortByColumn = "h.id";
                sortByType = "ASC";
            } else if (sortBy == 1) {
                sortByColumn = "h.id";
                sortByType = "DESC";
            } else if (sortBy == 2) {
                sortByColumn = "h.name";
                sortByType = "ASC";
            } else if (sortBy == 3) {
                sortByColumn = "h.name";
                sortByType = "DESC";
            } else if (sortBy == 4) {
                sortByColumn = "staff_count";
                sortByType = "DESC";
            } else if (sortBy == 5) {
                sortByColumn = "staff_count";
                sortByType = "ASC";
            }

            DefaultTableModel model = (DefaultTableModel) invoiceTable.getModel();
            model.setRowCount(0);
            
            ResultSet results = MySQL.execute("SELECT h.*, COUNT(s.nic) AS staff_count FROM hospital h "
                    + "LEFT JOIN staff s ON h.id = s.hospital_id "
                    + "WHERE h.id LIKE '%"+search+"%' OR h.name LIKE '%"+search+"%' "
                    + "GROUP BY h.id "
                    + "ORDER BY "+sortByColumn+" "+sortByType+" ");

            while (results.next()) {
                Vector v = new Vector();
                v.add(results.getString("id"));
                v.add(results.getString("name"));
                v.add(results.getString("staff_count"));
                
                model.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

